@app.after_request
def log_request_response(response): #Log requests and responses
   secret_list = []

   my_uuid = uuid.uuid4()
   uid_hex = my_uuid.hex # Generate unique identifier for each request
   raw = request.get_data(as_text=True)
   decoded = unquote_plus(raw)
   now = datetime.now()

   log_data = {
      "req": {
         "method": request.method,
         "url": request.url,
         "remote_addr": request.remote_addr, # obtains items from request and response 
         "event_id": uid_hex, #unique ID to identify each request
         "timestamp": now.strftime("%Y-%m-%d %H:%M:%S"),
         "headers": dict(request.headers), # request headers
         "data": decoded,
         "secrets": "None"
      },
      
      "res": {
         "status_code": response.status_code,
         "content_type": response.content_type,
         "response_length": response.calculate_content_length()
      }
   }

   for item in secrets:
      if item in log_data["req"]["data"]: #checks if the data in the request contains a secret
         secret_list.append(item)
   
   log_data["req"]["secrets"] = secret_list #add the entire list of secrets

   logger.info(json.dumps(log_data)) #Dump the info to the logger in JSON format
    
   return response


